"""
Jira Test Result Reporter

Handles posting test execution results back to Jira tickets.
Used by the consuming project's CI to report test status.
"""

import json
import logging
import os
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Optional

try:
    import requests  # type: ignore
except ImportError:
    requests = None

logger = logging.getLogger(__name__)


@dataclass
class JiraTestResult:
    """Test execution result data."""

    ticket_id: str
    test_name: str
    status: str  # "passed", "failed", "skipped"
    duration_ms: int
    error_message: Optional[str] = None
    test_file: Optional[str] = None
    timestamp: Optional[str] = None

    def __post_init__(self) -> None:
        if self.timestamp is None:
            self.timestamp = datetime.now(timezone.utc).isoformat()


class JiraReporter:
    """Reports test execution results back to Jira tickets."""

    def __init__(
        self,
        base_url: Optional[str] = None,
        username: Optional[str] = None,
        token: Optional[str] = None,
        dry_run: bool = False,
    ):
        """
        Initialize Jira reporter.

        Args:
            base_url: Jira base URL (defaults to JIRA_BASE env var)
            username: Jira username (defaults to JIRA_USER env var)
            token: Jira API token (defaults to JIRA_TOKEN env var)
            dry_run: If True, only log what would be sent (for testing)
        """
        self.base_url = base_url or os.getenv("JIRA_BASE")
        self.username = username or os.getenv("JIRA_USER")
        self.token = token or os.getenv("JIRA_TOKEN")
        self.dry_run = dry_run

        if not requests and not dry_run:
            raise ImportError("requests library is required for Jira integration")

        if not self.dry_run and not all([self.base_url, self.username, self.token]):
            raise ValueError(
                "Jira credentials must be provided via parameters or environment variables: "
                "JIRA_BASE, JIRA_USER, JIRA_TOKEN"
            )

    def report_test_result(self, result: JiraTestResult) -> bool:
        """
        Report a test result to the corresponding Jira ticket.

        Args:
            result: Test execution result

        Returns:
            True if successful, False otherwise
        """
        try:
            comment_body = self._format_test_result_comment(result)

            if self.dry_run:
                logger.info(
                    f"[DRY RUN] Would post to {result.ticket_id}: {comment_body}"
                )
                return True

            return self._post_comment_to_ticket(result.ticket_id, comment_body)

        except Exception as e:
            logger.error(f"Failed to report test result for {result.ticket_id}: {e}")
            return False

    def _format_test_result_comment(self, result: JiraTestResult) -> str:
        """Format test result as Jira comment."""
        status_emoji = {"passed": "✅", "failed": "❌", "skipped": "⏭️"}

        emoji = status_emoji.get(result.status, "❓")

        comment = f"{emoji} **Automated Test Result**\n\n"
        comment += f"**Test:** {result.test_name}\n"
        comment += f"**Status:** {result.status.upper()}\n"
        comment += f"**Duration:** {result.duration_ms}ms\n"
        comment += f"**Timestamp:** {result.timestamp}\n"

        if result.test_file:
            comment += f"**Test File:** `{result.test_file}`\n"

        if result.error_message and result.status == "failed":
            comment += f"\n**Error Details:**\n```\n{result.error_message}\n```\n"

        comment += "\n_This comment was automatically generated by the test automation framework._"

        return comment

    def _post_comment_to_ticket(self, ticket_id: str, comment: str) -> bool:
        """Post a comment to a Jira ticket."""
        if not requests:
            logger.error("requests library not available")
            return False

        url = f"{self.base_url}/rest/api/2/issue/{ticket_id}/comment"

        headers = {"Content-Type": "application/json", "Accept": "application/json"}

        payload = {"body": comment}

        try:
            response = requests.post(
                url,
                auth=(self.username, self.token),  # type: ignore
                headers=headers,
                json=payload,
                timeout=30,
            )

            if response.status_code == 201:
                logger.info(f"Successfully posted comment to {ticket_id}")
                return True
            else:
                logger.error(
                    f"Failed to post comment to {ticket_id}: {response.status_code} - {response.text}"
                )
                return False

        except requests.RequestException as e:
            logger.error(f"Request failed for {ticket_id}: {e}")
            return False

    def update_ticket_status(self, ticket_id: str, transition_name: str) -> bool:
        """
        Update ticket status (e.g., move to "Testing" or "Done").

        Args:
            ticket_id: Jira ticket ID
            transition_name: Name of the transition to execute

        Returns:
            True if successful, False otherwise
        """
        if self.dry_run:
            logger.info(f"[DRY RUN] Would transition {ticket_id} to {transition_name}")
            return True

        try:
            # First get available transitions
            transitions_url = (
                f"{self.base_url}/rest/api/2/issue/{ticket_id}/transitions"
            )

            response = requests.get(
                transitions_url, auth=(self.username, self.token), timeout=30
            )

            if response.status_code != 200:
                logger.error(
                    f"Failed to get transitions for {ticket_id}: {response.text}"
                )
                return False

            transitions = response.json().get("transitions", [])
            transition_id = None

            for transition in transitions:
                if transition["name"].lower() == transition_name.lower():
                    transition_id = transition["id"]
                    break

            if not transition_id:
                logger.error(
                    f"Transition '{transition_name}' not found for {ticket_id}"
                )
                return False

            # Execute the transition
            transition_url = f"{self.base_url}/rest/api/2/issue/{ticket_id}/transitions"

            payload = {"transition": {"id": transition_id}}

            response = requests.post(
                transition_url,
                auth=(self.username, self.token),
                headers={"Content-Type": "application/json"},
                json=payload,
                timeout=30,
            )

            if response.status_code == 204:
                logger.info(
                    f"Successfully transitioned {ticket_id} to {transition_name}"
                )
                return True
            else:
                logger.error(f"Failed to transition {ticket_id}: {response.text}")
                return False

        except Exception as e:
            logger.error(f"Failed to update ticket status for {ticket_id}: {e}")
            return False


def report_from_pytest_json(json_file: str, ticket_id: str) -> bool:
    """
    Parse pytest JSON output and report results to Jira.

    Args:
        json_file: Path to pytest JSON report
        ticket_id: Jira ticket ID to report to

    Returns:
        True if successful, False otherwise
    """
    try:
        with open(json_file, "r") as f:
            data = json.load(f)

        reporter = JiraReporter()

        # Report overall summary
        summary = data.get("summary", {})
        total = summary.get("total", 0)
        passed = summary.get("passed", 0)
        failed = summary.get("failed", 0)

        overall_status = "passed" if failed == 0 and total > 0 else "failed"

        result = JiraTestResult(
            ticket_id=ticket_id,
            test_name=f"Generated Test Suite ({total} tests)",
            status=overall_status,
            duration_ms=int(data.get("duration", 0) * 1000),
            error_message=f"Failed: {failed}, Passed: {passed}" if failed > 0 else None,
        )

        return reporter.report_test_result(result)

    except Exception as e:
        logger.error(f"Failed to parse pytest JSON output: {e}")
        return False


if __name__ == "__main__":
    # Example usage
    import sys

    if len(sys.argv) < 3:
        print("Usage: python jira_reporter.py <ticket_id> <status> [error_message]")
        sys.exit(1)

    ticket_id = sys.argv[1]
    status = sys.argv[2]
    error_message = sys.argv[3] if len(sys.argv) > 3 else None

    result = JiraTestResult(
        ticket_id=ticket_id,
        test_name="Generated Acceptance Test",
        status=status,
        duration_ms=1500,
        error_message=error_message,
        test_file="tests/generated/test_acceptance.py",
    )

    reporter = JiraReporter()
    success = reporter.report_test_result(result)

    sys.exit(0 if success else 1)
